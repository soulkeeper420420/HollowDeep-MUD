def pid():
    value=subprocess.check_output(['systemctl','show','hollowdeep.service','-p','MainPID','--value'],text=True).strip()
    if not value.isdigit() or int(value)<1: raise SystemExit('Expected running live service')
    return value

def main():
    os.umask(0o077)
    if len(sys.argv)!=2: raise SystemExit('Usage: onepass_linode.py VERIFIED_PRIVATE_DEITY_SRC')
    raw=Path(sys.argv[1]); src=raw.resolve(strict=True)
    dev=Path('/root/hollowdeep-dev')
    if raw.is_symlink() or src.name!='src' or src.parent.parent!=dev or not src.parent.name.startswith('necromancer-playtest-deity-'):
        raise SystemExit('Refusing nonprivate source')
    if any(x.is_symlink() for x in src.rglob('*')): raise SystemExit('Symlink source refused')
    if (src/'frp.new').open('rb').read(5)!=b'\x7fELF\x01': raise SystemExit('Missing accepted ELF32 input')
    before=pid()
    work=Path(tempfile.mkdtemp(prefix='necromancer-playtest-corpse-',dir=dev))
    pkg=work/'pkg'; pkg.mkdir()
    for name,body in PAYLOAD.items():
        dest=pkg/name; dest.parent.mkdir(parents=True,exist_ok=True); dest.write_text(body,encoding='utf-8')
    shutil.copytree(src,work/'src')
    print('PRIVATE CORPSE BUILD: '+str(work),flush=True)
    try:
        subprocess.run(['bash',str(pkg/'run_private.sh'),str(work/'src')],env=dict(os.environ,HD_TEST_ELF32='1'),check=True)
    finally:
        if pid()!=before: raise SystemExit('Protected service PID changed')
        print('PRODUCTION SERVICE PID: UNCHANGED',flush=True)
    print('CORPSE: COMBINED NECROMANCER/DEITY ELF32 PASS')
    print('PRIVATE SOURCE: '+str(work/'src'))

if __name__=='__main__': main()
